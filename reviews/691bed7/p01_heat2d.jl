using PDEStudio
const P = @__DIR__
studio_headless!()
set_save_path!(mktempdir())
launch_plotter(test_heat_2d(); style = :heatmap)
describe_studio()
@show studio_snapshot(joinpath(P, "p01_plots.png"))
@show studio_snapshot(joinpath(P, "p01_window.png"); area = :window)
println("--- zoom 4 around (0.25,0.25)")
@show studio_zoom!(4; center = (0.25, 0.25))
studio_snapshot(joinpath(P, "p01_zoom.png"))
println("--- move t slider; view should stay")
@show studio_set!(:t => 0.03)
@show studio_state().plots[1].xlims studio_state().plots[1].ylims
studio_snapshot(joinpath(P, "p01_zoom_t.png"))
println("--- surface")
studio_reset_view!()
@show studio_set!(:plot_style => :heatmap_surface)
@show studio_rotate!(60, 15)
studio_snapshot(joinpath(P, "p01_surface_rot.png"))
@show studio_zoom!(2)
studio_snapshot(joinpath(P, "p01_surface_zoom.png"))
println("--- compare methods")
studio_reset_view!()
@show studio_set!(:plot_style => :heatmap_flat, :compare_target => :methods, :compare_columns => 3)
s = studio_state(); @show length(s.plots) [p.title for p in s.plots]
studio_snapshot(joinpath(P, "p01_compare.png"))
studio_snapshot(joinpath(P, "p01_compare_p2.png"); plot = 2)
studio_snapshot(joinpath(P, "p01_compare_p3_2x.png"); plot = 3, px_per_unit = 2)
describe_studio()
