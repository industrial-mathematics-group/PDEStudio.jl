using PDEStudio, GLMakie
const P = @__DIR__
macro try_(ex)
    s = string(ex)
    quote
        try
            r = $(esc(ex)); println("OK   ", $s, " => ", r)
        catch e
            println("ERR  ", $s, " => ", typeof(e), ": ", first(sprint(showerror, e), 500))
        end
    end
end
GLMakie.activate!()
set_save_path!(mktempdir())
fig = launch_plotter(test_heat_2d(); style = :heatmap)
display(fig)
scr = Makie.getscreen(fig.scene)
info() = (ppu = scr.px_per_unit[], cfgppu = scr.config.px_per_unit, fb = GLMakie.GLFW.GetFramebufferSize(scr.glscreen), cb = size(Makie.colorbuffer(scr)))
@show info()
f = studio_snapshot(joinpath(P, "g04_ppu2.png"); px_per_unit = 2); @show size(Makie.FileIO.load(f))
@show info()
f = studio_snapshot(joinpath(P, "g04_ppu1.png")); @show size(Makie.FileIO.load(f))
@show info()
f = studio_snapshot(joinpath(P, "g04_ppu2_window.png"); area = :window, px_per_unit = 2); @show size(Makie.FileIO.load(f))
@show info()
println("--- after the snapshots, the window still renders at its resolution: native colorbuffer")
save(joinpath(P, "g04_native_after.png"), fig); @show size(Makie.FileIO.load(joinpath(P, "g04_native_after.png")))
println("--- HiDPI window (GLMakie.activate!(px_per_unit = 2))")
GLMakie.activate!(px_per_unit = 2)
reset_plotter!()
fig = launch_plotter(test_heat_2d(); style = :heatmap); display(fig)
scr = Makie.getscreen(fig.scene)
@show info()
f = studio_snapshot(joinpath(P, "g04_hidpi_default.png")); @show size(Makie.FileIO.load(f))
@show info()
f = studio_snapshot(joinpath(P, "g04_hidpi_ppu3.png"); px_per_unit = 3); @show size(Makie.FileIO.load(f))
@show info()
println("--- a render error inside the GLMakie branch: ppu restored?")
GLMakie.activate!(px_per_unit = 1)
reset_plotter!()
fig = launch_plotter(test_heat_2d(); style = :heatmap); display(fig)
scr = Makie.getscreen(fig.scene)
@show info()
