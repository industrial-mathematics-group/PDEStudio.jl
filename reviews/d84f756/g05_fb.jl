using PDEStudio, GLMakie
const P = @__DIR__
GLMakie.activate!()
set_save_path!(mktempdir())
fig = launch_plotter(test_heat_2d(); style = :heatmap)
display(fig)
scr = Makie.getscreen(fig.scene)
fb() = (ppu = scr.px_per_unit[], cfgppu = scr.config.px_per_unit, fb = size(scr.framebuffer), loop = !isnothing(scr.rendertask), sf = scr.scalefactor[])
sleep(1); @show fb()
studio_snapshot(joinpath(P, "g05_2x.png"); px_per_unit = 2)
@show fb()
sleep(1.5); @show fb()   # (the renderloop's next frame)
println("--- HiDPI")
GLMakie.activate!(px_per_unit = 2)
reset_plotter!()
fig = launch_plotter(test_heat_2d(); style = :heatmap); display(fig)
scr = Makie.getscreen(fig.scene)
sleep(1); @show fb()
studio_snapshot(joinpath(P, "g05_hidpi_1x.png"))
@show fb()
sleep(1.5); @show fb()
println("--- the window after a scale-factor change (what GLMakie does when the window moves to another monitor)")
scr.scalefactor[] = 1.5
sleep(1); @show fb()
println("END")
