using PDEStudio
const m = PDEStudio.manager
st() = (s = studio_state(); (axes_x = s.axes.x, title = s.plots[1].title, locked = s.camera_locked, xl = s.plots[1].xlims, yl = s.plots[1].ylims, api = PDEStudio._api_view_locked(), plotflag = m.flags[:Plot][], status = s.status.text))
studio_headless!(); set_save_path!(mktempdir())
launch_plotter(test_advection_1d())
println("--- A: pending x_axis => :t, then zoom, then Update Plot")
studio_set!(:x_axis => :t; apply = false); @show st()
studio_zoom!(4; center = (0.3, 0.5)); @show st()
@show studio_press!(:update_plot)
@show st()
studio_snapshot(joinpath(@__DIR__, "a06_A.png"))
studio_reset_view!(); studio_set!(:x_axis => :x); studio_reset_view!()
println("--- B: the same without the zoom")
studio_set!(:x_axis => :t; apply = false)
@show studio_press!(:update_plot)
@show st()
studio_set!(:x_axis => :x); studio_reset_view!()
println("--- C: pending style + y axis (heatmap, y = t), zoom, Apply Layout")
studio_set!(:plot_style => :heatmap_flat, :y_axis => :t; apply = false)
studio_zoom!(4; center = (0.3, 0.5)); @show st()
@show studio_press!(:apply_layout)
@show st() m.active_plot_type
studio_snapshot(joinpath(@__DIR__, "a06_C.png"))
println("END")
