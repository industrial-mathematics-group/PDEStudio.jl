using PDEStudio
const P = @__DIR__
macro try_(ex)
    s = string(ex)
    quote
        try
            r = $(esc(ex)); println("OK   ", $s, " => ", r)
        catch e
            println("ERR  ", $s, " => ", typeof(e), ": ", first(sprint(showerror, e), 300))
        end
    end
end
st() = (s = studio_state(); (locked = s.camera_locked, xl = s.plots[1].xlims, yl = s.plots[1].ylims, api = PDEStudio._api_view_locked(), status = s.status))
studio_headless!()
